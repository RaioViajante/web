import { projectArt } from "@raioviajante/design/projects";
import type { ProjectArtCopy } from "../../lib/projects";
import {
  roughEllipse,
  roughLine,
  roughRect,
  roughStar,
  starFill,
} from "../../lib/sketch";
import { Disc } from "./minis";
import { RefrainStage } from "./RefrainStage";

const scribbles = [150, 190, 120, 170];

/** A music note: a filled head and a stem, in rough ink. */
function Note({ className }: { className: string }) {
  return (
    <svg className={`rf-note ${className}`} viewBox="0 0 22 28">
      <path className="is-filled" d={roughEllipse(8, 22, 5, 3.6, 41, 0.08)} />
      <path d={roughLine(12.6, 21, 13, 3, 42, 0.5)} />
      <path d={roughLine(13, 3, 19, 8, 43, 0.5)} />
    </svg>
  );
}

/**
 * Refrain: the notebook it is drawn after (black ink on paper, the only color
 * from album art) and a record that plays when pressed. Every stroke is
 * generated by lib/sketch.ts; the words come from the locale's copy.
 */
export function RefrainSketch({ copy }: { copy: ProjectArtCopy }) {
  const text = copy.refrain;
  return (
    <RefrainStage
      label={copy.label.refrain}
      play={text.play}
      stop={text.stop}
      record={text.record}
      disc={
        <>
          <Disc className="rf-disc" />
          <svg className="rf-arm" viewBox="-80 -12 100 160" aria-hidden="true">
            <path d={roughLine(0, 0, -10, 70, 51, 1)} />
            <path d={roughLine(-10, 70, -58, 128, 52, 1)} />
            <path d={roughRect(-66, 124, 14, 10, 53, 0.8)} />
            <path
              className="is-filled"
              d={roughEllipse(0, 0, 7, 7, 54, 0.06)}
            />
          </svg>
        </>
      }
    >
      <div className="rf-page" aria-hidden="true">
        <svg
          className="rf-box"
          viewBox="0 0 400 300"
          preserveAspectRatio="none"
        >
          <path d={roughRect(4, 4, 392, 292, 1, 2.2)} />
        </svg>
        <span className="rf-holes">
          {Array.from({ length: 7 }, (_, index) => (
            <span key={index} />
          ))}
        </span>
        <div className="rf-inner">
          <p className="rf-nav">
            <span className="rf-nav__current">
              {text.albums}
              <svg viewBox="0 0 100 8" preserveAspectRatio="none">
                <path d={roughLine(0, 4, 100, 3, 61, 1.2)} />
              </svg>
            </span>
            <span>·</span>
            <span>{text.artists}</span>
            <span>·</span>
            <span>{text.memories}</span>
          </p>
          <p className="rf-title">{text.title}</p>
          <ol className="rf-tracks">
            {scribbles.map((width, index) => (
              <li key={index}>
                <span className="rf-tracks__number">
                  {String(index + 1).padStart(2, "0")}
                  {index === 2 ? (
                    <svg className="rf-tracks__circle" viewBox="-25 -16 50 32">
                      <path d={roughEllipse(0, 0, 21, 13, 71, 0.08)} />
                    </svg>
                  ) : null}
                </span>
                <svg
                  className="rf-tracks__line"
                  width={width}
                  height="10"
                  viewBox={`-2 -6 ${width + 4} 12`}
                >
                  <path d={roughLine(0, 0, width * 0.8, 0, 80 + index, 1.4)} />
                </svg>
              </li>
            ))}
          </ol>
          <span className="rf-stars">
            {Array.from({ length: 5 }, (_, index) => (
              <svg key={index} className="rf-star" viewBox="0 0 22 23">
                <path className="rf-star__fill" d={starFill(11, 12, 10)} />
                <path d={roughStar(11, 12, 10, 90 + index * 10)} />
              </svg>
            ))}
          </span>
          <p className="rf-tagline">{text.tagline}</p>
        </div>
      </div>
      <figure className="rf-sticker" aria-hidden="true">
        {/* eslint-disable-next-line @next/next/no-img-element -- fixed derivative */}
        <img
          src={projectArt.refrainSticker.src}
          alt=""
          width={92}
          height={92}
          loading="lazy"
          decoding="async"
        />
        <span className="rf-tape" />
      </figure>
      <svg className="rf-cassette" viewBox="-4 -4 128 84" aria-hidden="true">
        <path d={roughRect(0, 0, 120, 76, 101, 1.2)} />
        <path d={roughRect(16, 12, 88, 34, 105, 0.8)} />
        <path d={roughEllipse(38, 29, 8, 8, 109, 0.08)} />
        <path d={roughEllipse(82, 29, 8, 8, 110, 0.08)} />
        <path d={roughLine(26, 60, 94, 60, 111, 0.8)} />
      </svg>
      <span className="rf-notes" aria-hidden="true">
        <Note className="is-1" />
        <Note className="is-2" />
        <Note className="is-3" />
      </span>
    </RefrainStage>
  );
}
