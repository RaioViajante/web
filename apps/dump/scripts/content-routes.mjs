import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import matter from "gray-matter";

import {
  isPublishedPost,
  parseFrontmatter,
  slugFromFilename,
} from "../lib/content-schema.ts";
import { encodeTagSlug } from "../lib/tag-route.ts";

const app = join(dirname(fileURLToPath(import.meta.url)), "..");
const locales = ["en", "pt-BR"];
const prefix = { en: "", "pt-BR": "/pt" };

export function collectPublishedRoutes(postsDirectory, taxonomy) {
  const tagById = new Map(taxonomy.map((tag) => [tag.id, tag]));
  const posts = Object.fromEntries(locales.map((locale) => [locale, []]));
  const tags = Object.fromEntries(locales.map((locale) => [locale, new Set()]));

  for (const filename of readdirSync(postsDirectory).sort()) {
    if (!filename.endsWith(".mdx") || /^[._]/.test(filename)) continue;
    const slug = slugFromFilename(filename);
    const { data } = matter(
      readFileSync(join(postsDirectory, filename), "utf8"),
    );
    // The generator uses the content loader's complete record validation
    // before publication membership is decided. A malformed draft flag (or
    // any other malformed frontmatter) therefore fails both paths identically.
    const post = parseFrontmatter(data, slug);
    if (!isPublishedPost(post)) continue;

    posts[post.locale].push(`${prefix[post.locale]}/posts/${slug}`);
    for (const id of post.tags) {
      const presentation = tagById.get(id)?.locales?.[post.locale];
      if (!presentation)
        throw new Error(
          `${filename}: tag ${JSON.stringify(id)} has no ${post.locale} presentation`,
        );
      tags[post.locale].add(
        `${prefix[post.locale]}/tags/${encodeTagSlug(presentation.slug)}`,
      );
    }
  }

  return {
    posts,
    tags: Object.fromEntries(
      locales.map((locale) => [locale, [...tags[locale]].sort()]),
    ),
  };
}

const serialized = (value) => JSON.stringify(value, null, 2);

export function renderPublishedRoutes({ posts, tags }) {
  return (
    `// Generated by scripts/content-routes.mjs. Do not edit by hand.\n` +
    `export const publishedPostPaths = ${serialized(posts)} as const;\n\n` +
    `export const publishedTagPaths = ${serialized(tags)} as const;\n`
  );
}

export function generatePublishedRoutes() {
  const postsDirectory = join(app, "content", "posts");
  const taxonomy = JSON.parse(
    readFileSync(join(app, "content", "tags.json"), "utf8"),
  );
  const output = renderPublishedRoutes(
    collectPublishedRoutes(postsDirectory, taxonomy),
  );
  writeFileSync(join(app, "lib", "published-routes.generated.ts"), output);
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))
)
  generatePublishedRoutes();
