import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import matter from "gray-matter";

const app = join(dirname(fileURLToPath(import.meta.url)), "..");
const postsDirectory = join(app, "content", "posts");
const taxonomy = JSON.parse(readFileSync(join(app, "content", "tags.json")));
const tagById = new Map(taxonomy.map((tag) => [tag.id, tag]));
const locales = ["en", "pt-BR"];
const prefix = { en: "", "pt-BR": "/pt" };
const posts = Object.fromEntries(locales.map((locale) => [locale, []]));
const tags = Object.fromEntries(locales.map((locale) => [locale, new Set()]));

for (const filename of readdirSync(postsDirectory).sort()) {
  if (!filename.endsWith(".mdx") || /^[._]/.test(filename)) continue;
  const { data } = matter(readFileSync(join(postsDirectory, filename), "utf8"));
  if (data.draft === true) continue;
  if (!locales.includes(data.locale))
    throw new Error(
      `${filename}: unsupported locale ${JSON.stringify(data.locale)}`,
    );
  const slug = basename(filename, ".mdx");
  posts[data.locale].push(`${prefix[data.locale]}/posts/${slug}`);
  for (const id of data.tags ?? []) {
    const presentation = tagById.get(id)?.locales?.[data.locale];
    if (!presentation)
      throw new Error(
        `${filename}: tag ${JSON.stringify(id)} has no ${data.locale} presentation`,
      );
    tags[data.locale].add(
      `${prefix[data.locale]}/tags/${encodeURIComponent(presentation.slug)}`,
    );
  }
}

const serialized = (value) => JSON.stringify(value, null, 2);
const output =
  `// Generated by scripts/content-routes.mjs. Do not edit by hand.\n` +
  `export const publishedPostPaths = ${serialized(posts)} as const;\n\n` +
  `export const publishedTagPaths = ${serialized(
    Object.fromEntries(
      locales.map((locale) => [locale, [...tags[locale]].sort()]),
    ),
  )} as const;\n`;

writeFileSync(join(app, "lib", "published-routes.generated.ts"), output);
