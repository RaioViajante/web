/**
 * Derives the Stucco. case images from the local kit, which stays out of the
 * repository, and writes the module that imports them:
 *
 *   pnpm --filter @raioviajante/design stucco-art <path to the kit>
 *
 * Every width is capped below the single-image budget (perf/budgets.json) by
 * lowering the quality. Output never carries the sources' metadata.
 */
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { join, parse } from "node:path";
import sharp from "sharp";

export const ceiling = 140 * 1024;
const target = fileURLToPath(
  new URL("../assets/projects/stucco/", import.meta.url),
);
const moduleFile = fileURLToPath(
  new URL("../components/stucco.ts", import.meta.url),
);

async function derive(source, name, width, quality) {
  for (let q = quality; ; q -= 6) {
    const { data, info } = await sharp(source)
      .resize({ width, withoutEnlargement: true, kernel: "lanczos3" })
      .webp({ quality: q, effort: 6 })
      .toBuffer({ resolveWithObject: true });
    if (data.length <= ceiling || q <= 40) {
      if (data.length > ceiling) throw new Error(`${name} is too large`);
      await writeFile(join(target, name), data);
      return { name, width: info.width, height: info.height };
    }
  }
}

/** All widths of one source, plus how the module refers to them. */
async function variants(source, stem, widths, quality) {
  const out = [];
  for (const width of widths)
    out.push(await derive(source, `${stem}-${width}.webp`, width, quality));
  return out;
}

const identifier = (name) =>
  name
    .replace(/\.webp$/, "")
    .replace(/[^a-z0-9]+(.)/g, (_, char) => char.toUpperCase());

async function main(kit) {
  if (!kit) throw new Error("Pass the path to the kit");
  const manifest = JSON.parse(
    await readFile(join(kit, "reference/manifest.json"), "utf8"),
  );
  await rm(target, { recursive: true, force: true });
  await mkdir(target, { recursive: true });
  const imports = [];
  const use = (item) => {
    imports.push(item.name);
    return identifier(item.name);
  };
  const entry = (items) =>
    `image(${items.at(-1).width}, ${items.at(-1).height}, ${items
      .map((item) => `[${use(item)}, ${item.width}]`)
      .join(", ")})`;

  const tour = async (device, folder, widths, thumb) => {
    const steps = [];
    for (const [key, file, url, group] of manifest[folder]) {
      const source = join(kit, "prints", device, file);
      const stem = `${device}-${key.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}`;
      const full = await variants(source, stem, widths, 76);
      const [small] = await variants(source, `${stem}-thumb`, [thumb], 62);
      steps.push(
        `{ key: ${JSON.stringify(key)}, url: ${JSON.stringify(url)}, group: ${JSON.stringify(group)}, shot: ${entry(full)}, thumb: ${entry([small])} }`,
      );
    }
    return `[${steps.join(", ")}]`;
  };
  const desktop = await tour("desktop", "tour_desktop", [800, 1440], 240);
  const mobile = await tour("mobile", "tour_mobile", [320, 640], 120);

  const mockup = async (file, stem) =>
    entry(await variants(join(kit, "brand", file), stem, [800, 1480], 76));
  const cover = await mockup(manifest.brand_cover, "brand-cover");
  const pieces = [];
  for (const piece of manifest.brand_pieces) {
    const art = [];
    for (const file of piece.art)
      art.push(
        entry(
          await variants(
            join(kit, "brand", file),
            `art-${parse(file).name.replace(/-1080.*$/, "")}`,
            [640],
            90,
          ),
        ),
      );
    pieces.push(
      `{ key: ${JSON.stringify(piece.key)}, mockup: ${await mockup(piece.mockup, `brand-${piece.key}`)}, art: [${art.join(", ")}] }`,
    );
  }

  const photos = [];
  for (const { photo } of manifest.card_slideshow)
    photos.push(
      entry(
        await variants(
          join(kit, photo),
          `photo-${parse(photo).name}`,
          [480, 800],
          74,
        ),
      ),
    );

  await writeFile(
    moduleFile,
    `// Generated by scripts/stucco-art.mjs; never edit by hand.
// The images of the Stucco. client case, kept out of every other page's bundle.
${imports.map((name) => `import ${identifier(name)} from "../assets/projects/stucco/${name}";`).join("\n")}

type StaticAsset = string | { src: string };

const url = (asset: StaticAsset) =>
  typeof asset === "string" ? asset : asset.src;

export interface StuccoImage {
  src: string;
  srcSet: string;
  width: number;
  height: number;
}

const image = (
  width: number,
  height: number,
  ...variants: [StaticAsset, number][]
): StuccoImage => ({
  src: url(variants.at(-1)![0]),
  srcSet: variants.map(([asset, w]) => \`\${url(asset)} \${w}w\`).join(", "),
  width,
  height,
});

export const stuccoTour = { desktop: ${desktop}, mobile: ${mobile} } as const;
export const stuccoBrand = { cover: ${cover}, pieces: [${pieces.join(", ")}] } as const;
export const stuccoPhotos = [${photos.join(", ")}] as const;
`,
  );
  console.log(`${imports.length} images`);
}

if (process.argv[1] === fileURLToPath(import.meta.url))
  await main(process.argv[2]);
